/**
 * Composes media/manifest.yaml from the authoring fragments in media/fragments/*.yaml and the
 * content's media usage. Each entry's `prompt` is the full text that would be sent: era preamble,
 * subject, global suffix. Run by hand after editing a fragment:  node tools/media/compose.ts
 * This script makes no network calls and generates no images.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse, stringify } from 'yaml';
import { mediaUsage } from '../../content/media-usage.ts';
import { composePrompt, loadStyle, ROOT, type FragmentEntry, type ManifestEntry } from './lib.ts';

const style = loadStyle();
const dir = join(ROOT, 'media/fragments');
const entries: FragmentEntry[] = [];
for (const f of readdirSync(dir)
	.filter((f) => f.endsWith('.yaml'))
	.sort()) {
	const list = parse(readFileSync(join(dir, f), 'utf8')) as FragmentEntry[];
	entries.push(...list);
}

const usage = mediaUsage();
const errors: string[] = [];
const seen = new Set<string>();
const assets: ManifestEntry[] = [];
for (const e of entries.sort((a, b) => a.id.localeCompare(b.id))) {
	if (seen.has(e.id)) errors.push(`duplicate id ${e.id}`);
	seen.add(e.id);
	if (!style.eras[e.era]) errors.push(`${e.id}: unknown era ${e.era}`);
	if (!style.aspects[e.aspect]) errors.push(`${e.id}: unknown aspect ${e.aspect}`);
	const used = usage.get(e.id);
	if (!used) errors.push(`${e.id}: not used by any content`);
	assets.push({
		id: e.id,
		type: e.type,
		era: e.era,
		aspect: e.aspect,
		used_by: used ?? [],
		alt: e.alt.trim(),
		subject: e.subject.replace(/\s+/g, ' ').trim(),
		prompt: style.eras[e.era] ? composePrompt(style, e.era, e.subject) : ''
	});
}
for (const id of usage.keys())
	if (!seen.has(id)) errors.push(`${id}: referenced by content but missing a fragment`);
if (errors.length) {
	console.error(errors.join('\n'));
	process.exit(1);
}

const header = `# GENERATED by tools/media/compose.ts from media/fragments/*.yaml. Edit the fragments, then recompose.
# Every asset: id, type, where it is used, the full generation prompt, aspect, era and alt text.
`;
writeFileSync(join(ROOT, 'media/manifest.yaml'), header + stringify({ assets }, { lineWidth: 0 }));
console.log(`Manifest: ${assets.length} assets.`);
